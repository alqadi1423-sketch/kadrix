import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";

/**
 * File storage. Self-hosters get the local disk by default; an S3-compatible
 * implementation can be added behind the same interface for the cloud.
 */
export interface Storage {
  put(workspaceId: string, data: Uint8Array): Promise<string>;
  get(key: string): Promise<Uint8Array>;
  delete(key: string): Promise<void>;
}

export const MAX_UPLOAD_BYTES = 25 * 1024 * 1024;

export function createDiskStorage(root: string): Storage {
  const base = resolve(root);
  const pathOf = (key: string) => {
    // Keys are generated by us, but never trust them blindly.
    if (!/^[0-9a-f-]{36}\/[0-9a-f-]{36}$/.test(key)) throw new Error("bad storage key");
    return join(base, key);
  };
  return {
    async put(workspaceId, data) {
      const key = `${workspaceId}/${randomUUID()}`;
      const p = pathOf(key);
      await mkdir(dirname(p), { recursive: true });
      await writeFile(p, data);
      return key;
    },
    async get(key) {
      return readFile(pathOf(key));
    },
    async delete(key) {
      await rm(pathOf(key), { force: true });
    },
  };
}

export function createMemoryStorage(): Storage {
  const files = new Map<string, Uint8Array>();
  return {
    async put(workspaceId, data) {
      const key = `${workspaceId}/${randomUUID()}`;
      files.set(key, data);
      return key;
    },
    async get(key) {
      const f = files.get(key);
      if (!f) throw new Error("not found");
      return f;
    },
    async delete(key) {
      files.delete(key);
    },
  };
}
